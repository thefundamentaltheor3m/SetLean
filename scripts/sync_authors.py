#!/usr/bin/env python3

"""
This script propagates the author list in `CITATION.cff` to every other place that lists the
authors: the README, the website configuration and the blueprint.

Run it after editing `CITATION.cff` and commit the result. With `--check`, it writes nothing and
exits with an error if any of these files is out of date.
"""

import argparse
import json
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
CITATION = ROOT / 'CITATION.cff'
README = ROOT / 'README.md'
WEBSITE_CONFIG = ROOT / 'home_page' / '_config.yml'
BLUEPRINT_AUTHORS = ROOT / 'blueprint' / 'src' / 'authors.tex'

NOTICE = 'generated by scripts/sync_authors.py from CITATION.cff; do not edit by hand'

TEX_SPECIALS = {
    '\\': r'\textbackslash{}',
    '&': r'\&',
    '%': r'\%',
    '$': r'\$',
    '#': r'\#',
    '_': r'\_',
    '{': r'\{',
    '}': r'\}',
    '~': r'\textasciitilde{}',
    '^': r'\textasciicircum{}',
}

def load_authors():
    """
    Read the author list from `CITATION.cff`.

    Returns:
        list[dict]: The authors, as CFF person or entity objects.
    """
    with open(CITATION, encoding='utf-8') as file:
        citation = yaml.safe_load(file)
    authors = citation.get('authors') or []
    if not authors:
        sys.exit('error: CITATION.cff lists no authors')
    for author in authors:
        for key, value in author.items():
            # YAML reads unquoted values such as `No` or `1e3` as booleans or numbers
            if not isinstance(value, str):
                sys.exit(f'error: {key}: {value!r} in CITATION.cff is not a string; quote it')
    return authors

def full_name(author):
    """
    Format a CFF author as a single name, e.g. "Ludwig van Beethoven, Jr.".

    Arguments:
        author (dict): A CFF person or entity object.
    """
    if 'name' in author:  # An entity, such as an organisation
        return author['name']
    parts = [author.get(key) for key in ('given-names', 'name-particle', 'family-names')]
    name = ' '.join(part for part in parts if part)
    if author.get('name-suffix'):
        name += ', ' + author['name-suffix']
    return name

def sentence(names):
    """
    Join names as in prose, matching Jekyll's `array_to_sentence_string` filter.

    Arguments:
        names (list[str]): The names to join.
    """
    if len(names) <= 2:
        return ' and '.join(names)
    return ', '.join(names[:-1]) + ', and ' + names[-1]

def tex_escape(text):
    """
    Escape the characters that are special in TeX.

    Arguments:
        text (str): The text to escape.
    """
    return ''.join(TEX_SPECIALS.get(char, char) for char in text)

def markdown_escape(text):
    """
    Escape the characters that could be read as Markdown or HTML markup.

    Arguments:
        text (str): The text to escape.
    """
    return re.sub(r'([\\`*_\[\]<>])', r'\\\1', text)

def replace_region(path, start, end, body):
    """
    Replace the lines strictly between the line containing `start` and the next `end` in a file.

    Arguments:
        path (pathlib.Path): The file containing the markers.
        start (str): The start marker; the rest of its line is kept as is.
        end (str): The end marker.
        body (str): The new contents of the region, ending in a newline.

    Returns:
        str: The new contents of the file.
    """
    text = path.read_text(encoding='utf-8')
    i = text.find(start)
    j = text.find(end, i)
    if i == -1 or j == -1:
        sys.exit(f'error: could not find the {start!r} and {end!r} markers in '
                 f'{path.relative_to(ROOT)}')
    i = text.index('\n', i) + 1
    return text[:i] + body + text[j:]

def render_readme(authors):
    """
    Render `README.md`, with each author linked to their ORCID or website if they have one.

    Arguments:
        authors (list[dict]): The CFF authors.
    """
    lines = []
    for author in authors:
        name = markdown_escape(full_name(author))
        link = author.get('orcid') or author.get('website')
        lines.append(f'- [{name}]({link})' if link else f'- {name}')
    body = '\n'.join(lines) + '\n'
    return replace_region(README, '<!-- AUTHORS:START', '<!-- AUTHORS:END -->', body)

def render_website_config(names):
    """
    Render `home_page/_config.yml`. Its `description` is the site's tagline, and the footer of
    `home_page/_layouts/default.html` reads `authors`.

    Arguments:
        names (list[str]): The authors' names.
    """
    # A JSON string is also a valid double-quoted YAML string
    body = f'description: {json.dumps("by " + sentence(names), ensure_ascii=False)}\nauthors:\n'
    body += ''.join(f'  - {json.dumps(name, ensure_ascii=False)}\n' for name in names)
    return replace_region(WEBSITE_CONFIG, '# AUTHORS:START', '# AUTHORS:END', body)

def render_blueprint_authors(names):
    """
    Render `blueprint/src/authors.tex`, which `print.tex` and `web.tex` include.

    Arguments:
        names (list[str]): The authors' names.
    """
    names = [tex_escape(name) for name in names]
    authors = r' \and '.join(names)
    return (f'% This file is {NOTICE}.\n'
            f'% For LaTeX, whose `\\maketitle` sets the authors side by side.\n'
            f'\\newcommand{{\\projectauthors}}{{{authors}}}\n'
            f'% For plasTeX, which does not support `\\and`.\n'
            f'\\newcommand{{\\projectauthorsentence}}{{{sentence(names)}}}\n')

def main():
    """
    Regenerate every file that lists the authors, or check that they are up to date.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true',
                        help='report out-of-date files and fail instead of updating them')
    args = parser.parse_args()

    authors = load_authors()
    names = [full_name(author) for author in authors]
    outputs = {
        README: render_readme(authors),
        WEBSITE_CONFIG: render_website_config(names),
        BLUEPRINT_AUTHORS: render_blueprint_authors(names),
    }
    stale = {path: content for path, content in outputs.items()
             if not path.exists() or path.read_text(encoding='utf-8') != content}

    for path, content in stale.items():
        if args.check:
            print(f'{path.relative_to(ROOT)} is out of date with CITATION.cff')
        else:
            path.write_text(content, encoding='utf-8')
            print(f'updated {path.relative_to(ROOT)}')
    if args.check and stale:
        sys.exit('run `python3 scripts/sync_authors.py` and commit the result')

if __name__ == '__main__':
    main()
